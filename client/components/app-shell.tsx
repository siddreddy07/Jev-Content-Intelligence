"use client"

import Link from "next/link"
import { usePathname } from "next/navigation"
import {
  LayoutDashboard,
  Moon,
  Plus,
  ScanSearch,
  Sun,
  Video,
} from "lucide-react"
import { useTheme } from "next-themes"

import { Button } from "@/components/ui/button"
import {
  Breadcrumb,
  BreadcrumbItem,
  BreadcrumbList,
  BreadcrumbPage,
} from "@/components/ui/breadcrumb"
import { Separator } from "@/components/ui/separator"
import {
  Sidebar,
  SidebarContent,
  SidebarFooter,
  SidebarGroup,
  SidebarGroupContent,
  SidebarHeader,
  SidebarInset,
  SidebarMenu,
  SidebarMenuButton,
  SidebarMenuItem,
  SidebarProvider,
  SidebarRail,
  SidebarTrigger,
} from "@/components/ui/sidebar"

const nav = [
  { title: "Dashboard", href: "/", icon: LayoutDashboard },
  { title: "Analyses", href: "/analyses", icon: ScanSearch },
  { title: "Video explorer", href: "/videos", icon: Video },
]

const titles: Record<string, string> = {
  "/": "Dashboard",
  "/analyze": "New analysis",
  "/analyses": "Analyses",
  "/videos": "Video explorer",
}

export function AppShell({ children }: { children: React.ReactNode }) {
  const pathname = usePathname()
  const { resolvedTheme, setTheme } = useTheme()

  return (
    <SidebarProvider>
      <Sidebar collapsible="icon">
        <SidebarHeader className="h-14 justify-center border-b border-sidebar-border px-3">
          <Link
            href="/"
            className="flex items-center gap-2.5 rounded-md outline-none focus-visible:ring-2 focus-visible:ring-sidebar-ring"
          >
            <svg viewBox="0 0 24 24" className="size-7 shrink-0" aria-hidden>
              <rect
                width="24"
                height="24"
                rx="6"
                className="fill-sidebar-primary"
              />
              {/* waveform resolving into a "J" stem: the opening seconds of a video */}
              <path
                d="M5 12h.01M8 9.5v5M11 6.5v8.5a3 3 0 0 1-3 3M14 10v4M17 11.2v1.6M19.5 12h.01"
                className="stroke-sidebar-primary-foreground"
                strokeWidth="1.8"
                strokeLinecap="round"
                fill="none"
              />
            </svg>
            <span className="font-heading text-[15px] font-semibold tracking-tight group-data-[collapsible=icon]:hidden">
              Jev
              <span className="ml-1.5 font-normal text-sidebar-foreground/60">
                Content Intelligence
              </span>
            </span>
          </Link>
        </SidebarHeader>

        <SidebarContent>
          <SidebarGroup className="group-data-[collapsible=icon]:hidden">
            <Button asChild size="sm" className="w-full justify-start gap-2">
              <Link href="/analyze">
                <Plus className="size-4" />
                Analyze a creator
              </Link>
            </Button>
          </SidebarGroup>
          <SidebarGroup>
            <SidebarGroupContent>
              <SidebarMenu>
                {nav.map((item) => (
                  <SidebarMenuItem key={item.href}>
                    <SidebarMenuButton
                      asChild
                      tooltip={item.title}
                      isActive={
                        item.href === "/"
                          ? pathname === "/"
                          : pathname.startsWith(item.href)
                      }
                    >
                      <Link href={item.href}>
                        <item.icon />
                        <span>{item.title}</span>
                      </Link>
                    </SidebarMenuButton>
                  </SidebarMenuItem>
                ))}
              </SidebarMenu>
            </SidebarGroupContent>
          </SidebarGroup>
        </SidebarContent>

        <SidebarFooter className="border-t border-sidebar-border group-data-[collapsible=icon]:hidden">
          <p className="px-2 py-1 text-xs leading-relaxed text-sidebar-foreground/60">
            Measured metrics come from YouTube. Interpretations are generated by
            AI and marked as such.
          </p>
        </SidebarFooter>
        <SidebarRail />
      </Sidebar>

      <SidebarInset>
        <header className="sticky top-0 z-10 flex h-14 shrink-0 items-center gap-2 border-b bg-background/90 px-4 backdrop-blur">
          <SidebarTrigger className="-ml-1" />
          <Separator
            orientation="vertical"
            className="mr-1 data-[orientation=vertical]:h-4"
          />
          <Breadcrumb>
            <BreadcrumbList>
              <BreadcrumbItem>
                <BreadcrumbPage className="font-medium">
                  {titles[pathname] ??
                    (pathname.endsWith("/snapshot")
                      ? "Creator snapshot"
                      : pathname.startsWith("/analyses/")
                        ? "Analysis progress"
                        : "Jev")}
                </BreadcrumbPage>
              </BreadcrumbItem>
            </BreadcrumbList>
          </Breadcrumb>
          <Button
            variant="ghost"
            size="icon"
            className="ml-auto"
            aria-label="Toggle color theme"
            onClick={() =>
              setTheme(resolvedTheme === "dark" ? "light" : "dark")
            }
          >
            <Sun className="size-4 dark:hidden" />
            <Moon className="hidden size-4 dark:block" />
          </Button>
        </header>
        <main className="mx-auto w-full max-w-6xl flex-1 px-4 py-8 md:px-8">
          {children}
        </main>
      </SidebarInset>
    </SidebarProvider>
  )
}
