function isActive(pathname: string, href: string) {
  return href === "/" ? pathname === "/" : pathname.startsWith(href)
}

export function AppSidebar() {
  const pathname = usePathname()

  return (
    <Sidebar collapsible="icon">
      <SidebarHeader className="h-14 justify-center border-b border-sidebar-border px-3">
        <Link
          href="/"
          className="flex items-center gap-2.5 rounded-md outline-none focus-visible:ring-2 focus-visible:ring-sidebar-ring"
        >
          <JevMark />
          <span className="font-heading text-[15px] font-semibold tracking-tight group-data-[collapsible=icon]:hidden">
            Jev
            <span className="ml-1.5 font-normal text-sidebar-foreground/60">
              Content Intelligence
            </span>
          </span>
        </Link>
      </SidebarHeader>

      <SidebarContent>
        <SidebarGroup className="group-data-[collapsible=icon]:hidden">
          <Button asChild size="sm" className="w-full justify-start gap-2">
            <Link href="/analyze">
              <Plus className="size-4" />
              Analyze a creator
            </Link>
          </Button>
        </SidebarGroup>

        <SidebarGroup>
          <SidebarGroupContent>
            <SidebarMenu>
              {primaryNav.map((item) => (
                <SidebarMenuItem key={item.href}>
                  <SidebarMenuButton
                    asChild
                    tooltip={item.title}
                    isActive={isActive(pathname, item.href)}
                  >
                    <Link href={item.href}>
                      <item.icon />
                      <span>{item.title}</span>
                    </Link>
                  </SidebarMenuButton>
                </SidebarMenuItem>
              ))}
            </SidebarMenu>
          </SidebarGroupContent>
        </SidebarGroup>
      </SidebarContent>

      <SidebarFooter className="border-t border-sidebar-border group-data-[collapsible=icon]:hidden">
        <p className="px-2 py-1 text-xs leading-relaxed text-sidebar-foreground/60">
          Measured metrics come from YouTube. Interpretations are generated by
          AI and marked as such.
        </p>
      </SidebarFooter>
      <SidebarRail />
    </Sidebar>
  )
}
